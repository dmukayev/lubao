import { calculatePalletsEuro, calculateVolumeM3 } from './body-size';

describe('body-size — задача 033, п.3/13', () => {
  it('стандартный полуприцеп 13.6×2.45 → 33 европаллеты (индустриальный стандарт, не 34 «впритык»)', () => {
    expect(calculatePalletsEuro(13.6, 2.45)).toBe(33);
  });

  it('одиночка 7.2×2.45 → 18 европаллет', () => {
    expect(calculatePalletsEuro(7.2, 2.45)).toBe(18);
  });

  it('задача 038, п.5 — ширина 2.40 м не теряет ряд из-за плавающей точки (2.4/0.8 = 2.999…)', () => {
    expect(calculatePalletsEuro(13.6, 2.4)).toBe(33);
    expect(calculatePalletsEuro(7.2, 2.4)).toBe(18);
  });

  it('учитывает поворот паллеты, когда раскладка «короткой стороной вдоль» выгоднее', () => {
    // Узкий кузов 2.0 м: стандартно — 2 ряда по ширине (floor(2.0/0.8)=2),
    // повёрнуто — floor(2.0/1.2)=1 колонна; длина 6 м: 5×2=10 против
    // floor(5.95/0.8)=7×1=7 → стандартная раскладка побеждает. А вот кузов
    // 1.0 м шириной: стандартно floor(1.0/0.8)=1 → 5; повёрнуто
    // floor(1.0/1.2)=0 → 0. Разворот в обратную сторону: длина 2.5, ширина
    // 2.5: стандарт 2×3=6, поворот floor(2.45/0.8)=3×2=6 — равны.
    expect(calculatePalletsEuro(6.0, 2.0)).toBe(10);
  });

  it('нулевые/отрицательные размеры → 0, без исключений', () => {
    expect(calculatePalletsEuro(0, 2.45)).toBe(0);
    expect(calculatePalletsEuro(13.6, 0)).toBe(0);
    expect(calculateVolumeM3(0, 1, 1)).toBe(0);
  });

  it('объём считается и округляется до 0.1 м³', () => {
    expect(calculateVolumeM3(13.6, 2.45, 2.7)).toBe(90.0);
    expect(calculateVolumeM3(7.2, 2.45, 2.4)).toBe(42.3);
  });
});
